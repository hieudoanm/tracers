/// Resolve an unresolved receiver qualifier (`fmt.Println`,
/// `serde_json::json!`, `os.path.join`, `console.log`, `JSON.parse`) to an
/// external qualified name when the qualifier is a known stdlib package or
/// a declared manifest dependency.
///
/// `member` is the called member name; the result is `{qualifier}.{member}`.
pub(crate) fn receiver_external_target(
    language: Language,
    receiver: &str,
    member: &str,
    external_deps: &std::collections::BTreeSet<String>,
) -> Option<String> {
    // Receivers must be plausible qualifier paths: identifiers joined by
    // `.`, `::`, or `/`. Reject expressions, keywords, and noise.
    if receiver.is_empty()
        || receiver.len() > 200
        || !receiver
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | ':' | '/' | '$'))
    {
        return None;
    }
    if matches!(
        receiver,
        "self" | "this" | "super" | "Self" | "crate" | "new" | "this?"
    ) {
        return None;
    }

    let in_stdlib = match language {
        Language::Go => GO_STDLIB_PACKAGES.contains(&receiver),
        Language::Python => PY_STDLIB_MODULES.contains(&receiver),
        Language::TypeScript | Language::Tsx | Language::JavaScript | Language::Jsx => {
            TS_GLOBAL_OBJECTS.contains(&receiver)
        }
        Language::Ruby => RUBY_STDLIB_MODULES.contains(&receiver),
        Language::Rust => {
            receiver.starts_with("std::")
                || receiver.starts_with("core::")
                || receiver.starts_with("alloc::")
        }
        _ => false,
    };
    if in_stdlib {
        return Some(format!("{receiver}.{member}"));
    }

    // Test-framework receiver objects: `expect(x).toBe(y)` → `expect.toBe`,
    // `screen.getByText(...)` → `screen.getByText`, `vi.fn()` → `vi.fn`.
    if matches!(
        language,
        Language::TypeScript | Language::Tsx | Language::JavaScript | Language::Jsx
    ) && TS_TEST_RECEIVERS.contains(&receiver)
    {
        return Some(format!("{receiver}.{member}"));
    }

    // Declared manifest dependency: match the full receiver, its last
    // segment (`github.com/x/y` imported as `y`), or — for `::` paths —
    // its first segment (`serde_json::de::Value` → crate `serde_json`).
    let dep_match = |candidate: &str| {
        external_deps
            .iter()
            .any(|dep| dep.eq_ignore_ascii_case(candidate))
    };
    if dep_match(receiver) {
        return Some(format!("{receiver}.{member}"));
    }
    let last = receiver.rsplit(['.', ':', '/']).next().unwrap_or("");
    if !last.is_empty() && last != receiver && dep_match(last) {
        return Some(format!("{receiver}.{member}"));
    }
    if receiver.contains("::") {
        if let Some(first) = receiver.split("::").next() {
            if !first.is_empty() && dep_match(first) {
                return Some(format!("{receiver}.{member}"));
            }
        }
    }
    None
}

