//! Language builtin / standard-library call targets.
//!
//! Calls that cannot resolve to an internal symbol but match a well-known
//! stdlib/prelude name are reported as `resolved_external` edges to a
//! canonical `std::*`, `builtin::*`, `lib::*`, or `builtins::*` symbol
//! instead of `unresolved` placeholder nodes. This keeps `roots`,
//! `impact`, and `callers` queries useful through ubiquitous calls like
//! `unwrap`, `expect`, `len`, `map`, or `print`.
//!
//! The tables are deliberately conservative name lists; they approximate
//! the language prelude/stdlib and common prototype methods. A match only
//! fires after internal/import resolution has already failed.

