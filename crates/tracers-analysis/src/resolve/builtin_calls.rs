/// Canonical qualified name for a builtin call, e.g. `std::unwrap`.
///
/// Returns `None` for languages without a table or names not in the table.
pub(crate) fn builtin_qualified(language: Language, name: &str) -> Option<String> {
    let (table, prefix) = match language {
        Language::Rust => (RUST_BUILTINS, "std"),
        Language::Go => (GO_BUILTINS, "builtin"),
        Language::TypeScript | Language::Tsx | Language::JavaScript | Language::Jsx => {
            (TS_BUILTINS, "lib")
        }
        Language::Python => (PYTHON_BUILTINS, "builtins"),
        _ => return None,
    };
    if table.binary_search(&name).is_ok() {
        return Some(format!("{prefix}::{name}"));
    }
    // Test-framework globals (`describe`, `it`, `expect`, jest-dom matchers,
    // Testing Library queries) used as bare calls in test files.
    if matches!(
        language,
        Language::TypeScript | Language::Tsx | Language::JavaScript | Language::Jsx
    ) && TS_TEST_GLOBALS.contains(&name)
    {
        return Some(format!("test::{name}"));
    }
    None
}

